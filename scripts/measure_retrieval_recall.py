#!/usr/bin/env python3
"""
Measures retrieval quality for LoreDocs using FTS5 search.
Tests recall@5 and skip rate on a fixed corpus.

Runtime: ~2-5 seconds on a local machine (creates a temp vault, indexes
~10-20 fixture docs via FTS5, runs ~10-15 queries). No network calls.
Cost: $0 -- purely local SQLite + FTS5, no API calls.

Persistence: --persist-to appends a JSONL line per run to the given file
(typically data/retrieval_recall_history.jsonl). The LAC dashboard reads
this file to display recall trends over time.
"""

import argparse
import json
import logging
import os
import sys
import tempfile
from datetime import datetime
from pathlib import Path

logging.basicConfig(level=logging.INFO, format='%(levelname)s: %(message)s')
logger = logging.getLogger(__name__)

def load_corpus(path: str) -> dict:
    """Load the retrieval corpus from a JSON file."""
    try:
        with open(path, 'r') as f:
            return json.load(f)
    except Exception as e:
        logger.error(f"Failed to load corpus from {path}: {e}")
        sys.exit(1)

def get_storage(root_path):
    """Import and return VaultStorage instance.

    VaultStorage expects a root directory Path (where it creates
    loredocs.db and vaults/), NOT a db file path. SH-106092: the
    original code passed a string db_path which caused a TypeError
    at runtime because VaultStorage.__init__ calls root.mkdir().
    """
    from pathlib import Path

    loredocs_path = Path(__file__).parent.parent
    sys.path.insert(0, str(loredocs_path))

    from loredocs.storage import VaultStorage
    root = Path(root_path) if not isinstance(root_path, Path) else root_path
    return VaultStorage(root)

def create_test_vault(storage, corpus: dict) -> str:
    """Create a vault with test documents. Returns vault_id.

    SH-106092: original code called add_document(doc_id=...) which does
    not match the VaultStorage API. Use add_document_from_text() which
    takes vault_id, name, text_content, filename.
    """
    try:
        vault_meta = storage.create_vault("test_corpus")
        vault_id = vault_meta["id"]  # create_vault returns a dict, not a string
        for doc in corpus.get('docs', []):
            doc_id = doc.get('id', 'unknown')
            title = doc.get('title', doc_id)
            body = doc.get('body', '')
            filename = f"{doc_id}.md"
            storage.add_document_from_text(
                vault_id=vault_id,
                name=doc_id,  # Use corpus doc_id as name for matching
                text_content=body,
                filename=filename,
            )
        return vault_id
    except Exception as e:
        logger.error(f"Failed to create test vault: {e}")
        raise

def run_recalls(storage, vault_id: str, queries: list, limit: int = 5) -> dict:
    """
    Run FTS5 searches and compute recall@5 and skip rate.
    """
    successful = 0
    skip_count = 0
    failed_queries = []

    for q in queries:
        query_text = q.get('text', '')
        expected_docs = set(q.get('expected_docs', []))
        query_id = q.get('id', 'unknown')

        try:
            result = storage.search(query_text, vault_id=vault_id, limit=limit)
            if result.get('error'):
                logger.warning(f"Query '{query_text}' has FTS error: {result['error']}")
                if q.get('expect_skip'):
                    successful += 1
                else:
                    skip_count += 1
                    failed_queries.append({
                        'query': query_text,
                        'expected': list(expected_docs),
                        'found': [],
                        'reason': f"FTS error: {result['error']}"
                    })
                continue

            # SH-106092: match on doc_name (which we set to corpus doc_id)
            # instead of doc_id (which is a UUID generated by storage).
            found_docs = set(r.get('doc_name') for r in result.get('results', []))

            if len(found_docs) == 0:
                if q.get('expect_skip'):
                    successful += 1
                else:
                    skip_count += 1
                    failed_queries.append({
                        'query': query_text,
                        'expected': list(expected_docs),
                        'found': [],
                        'reason': 'No results returned'
                    })
                continue

            if expected_docs.issubset(found_docs) or len(expected_docs) == 0:
                successful += 1
            else:
                failed_queries.append({
                    'query': query_text,
                    'expected': list(expected_docs),
                    'found': list(found_docs),
                    'reason': 'Missing expected documents'
                })

        except Exception as e:
            logger.error(f"Search failed for query '{query_text}': {e}")
            failed_queries.append({
                'query': query_text,
                'expected': list(expected_docs),
                'found': [],
                'reason': f'Exception: {str(e)}'
            })

    total = len(queries)
    recall_at_5 = successful / total if total > 0 else 0.0
    skip_rate = skip_count / total if total > 0 else 0.0

    return {
        'recall_at_5': recall_at_5,
        'skip_rate': skip_rate,
        'successful': successful,
        'skip_count': skip_count,
        'total_queries': total,
        'failed_queries': failed_queries
    }

def main():
    parser = argparse.ArgumentParser(description="Measure LoreDocs retrieval quality using FTS5")
    parser.add_argument('--corpus', required=True, help='Path to retrieval corpus JSON')
    parser.add_argument('--persist-to', help='Append result to this file (JSONL)')
    parser.add_argument('--recall-threshold', type=float, default=0.95, help='Minimum recall@5')
    parser.add_argument('--skip-threshold', type=float, default=0.05, help='Max allowed skip rate')
    args = parser.parse_args()

    corpus = load_corpus(args.corpus)
    queries = corpus.get('queries', [])
    docs = corpus.get('docs', [])

    if not queries:
        logger.error("Corpus has no queries")
        sys.exit(1)

    with tempfile.TemporaryDirectory() as tmpdir:
        # SH-106092: pass the temp dir as root Path, not a db file path.
        # VaultStorage creates loredocs.db and vaults/ under root.
        storage = get_storage(Path(tmpdir))
        try:
            vault_id = create_test_vault(storage, corpus)
            metrics = run_recalls(storage, vault_id, queries)
        except Exception as e:
            logger.error(f"Failed to run recall test: {e}")
            sys.exit(1)

    from datetime import timezone as dt_tz
    now = datetime.now(dt_tz.utc).isoformat()  # SH-106092: timezone-aware UTC
    commit = os.environ.get('GITHUB_SHA', os.environ.get('GIT_COMMIT', 'unknown'))
    version = os.environ.get('LOREDOCS_VERSION', 'unknown')

    result = {
        'timestamp': now,
        'commit': commit,
        'version': version,
        'recall_at_5': round(metrics['recall_at_5'], 4),
        'skip_rate': round(metrics['skip_rate'], 4),
        'corpus_size': metrics['total_queries'],
        'successful': metrics['successful'],
        'skip_count': metrics['skip_count'],
        'failed_queries': metrics['failed_queries'][:10],
        'status': 'pass'
    }

    if metrics['recall_at_5'] < args.recall_threshold:
        result['status'] = 'fail'
        logger.error(f"Recall@5 {metrics['recall_at_5']:.3f} below threshold {args.recall_threshold}")

    if metrics['skip_rate'] > args.skip_threshold:
        result['status'] = 'fail'
        logger.error(f"Skip rate {metrics['skip_rate']:.3f} above threshold {args.skip_threshold}")

    print(json.dumps(result, indent=2))

    if args.persist_to:
        try:
            Path(args.persist_to).parent.mkdir(parents=True, exist_ok=True)
            with open(args.persist_to, 'a') as f:
                f.write(json.dumps(result) + '\n')
        except Exception as e:
            logger.warning(f"Could not persist to {args.persist_to}: {e}")

    sys.exit(0 if result['status'] == 'pass' else 1)

if __name__ == '__main__':
    main()
